r"""gen_data.py: data\gems.json + data\rumours.txt -> main\r6\scripts\WhispersNC\WNC_Data.reds + data\RUMOURS_review.txt.
data\gems.json comes from tools\import_gems.py (positions / shard titles checked against the game journal)."""

import json, os, re

H = os.path.dirname(os.path.abspath(__file__))
gems = json.load(open(os.path.join(H, "data", "gems.json"), encoding="utf-8"))
assert [g["id"] for g in gems] == list(range(1, len(gems) + 1)), (
    "gem ids must be contiguous 1..n"
)
KIND = {"shard": 0, "area": 1, "fact": 2, "mail": 3}
FIRST_DT = min(g["id"] for g in gems if g["set"] == "dogtown")
assert all((g["set"] == "dogtown") == (g["id"] >= FIRST_DT) for g in gems), (
    "Dogtown gems must come last"
)

pools, cur = {}, None
for line in open(os.path.join(H, "data", "rumours.txt"), encoding="utf-8"):
    s = line.strip()
    if not s or s.startswith("#"):
        continue
    m = re.fullmatch(r"\[(\w+)\]", s)
    if m:
        cur = pools.setdefault(m.group(1), [])
        continue
    assert cur is not None and '"' not in s and "\\" not in s and "|" not in s, s
    cur.append(s)
need = {g["pool"] for g in gems}
assert all(pools.get(k) for k in need), (need, pools.keys())

seen = {k: 0 for k in pools}
rows = []
for g in gems:
    c = g["pool"]
    line = pools[c][seen[c] % len(pools[c])]  # spread evenly through the pool
    seen[c] += 1
    for p in g["pre"]:
        assert re.fullmatch(
            r"(FACT|NOFACT) \w+|FACTGE \w+ \d+|SHARD LocKey#\d+|AFTER \d+", p
        ), p
    assert "|" not in g["loc"] and '"' not in g["loc"]
    rows.append((g, line))


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def arr(vals):
    out, cur_ = [], ""
    for v in vals:
        if len(cur_) + len(v) > 110:
            out.append(cur_)
            cur_ = ""
        cur_ += v + ", "
    out.append(cur_)
    return (
        "[\n      " + "\n      ".join(o.rstrip() for o in out).rstrip(",") + "\n    ]"
    )


f = lambda v: "%.3f" % v


def fn(name, typ, vals):
    return "  public static func %s() -> array<%s> {\n    return %s;\n  }" % (
        name,
        typ,
        arr(vals),
    )


src = [
    "// GENERATED by gen_data.py from data\\gems.json + data\\rumours.txt. Do not edit: edit those and re-run.",
    "// Index i = gem id - 1. Kind: 0 shard (journal title), 1 spot (no shard: position + radius), 2 vanilla fact,",
    "// 3 computer mail (title). Ids %d..%d are Dogtown (Phantom Liberty)."
    % (FIRST_DT, len(gems)),
    "public abstract class WNCData {",
    "  public static func FirstDogtown() -> Int32 = %d" % FIRST_DT,
    fn("X", "Float", [f(g["x"]) for g, _ in rows]),
    fn("Y", "Float", [f(g["y"]) for g, _ in rows]),
    fn("Z", "Float", [f(g["z"]) for g, _ in rows]),
    fn("R", "Float", [f(g.get("r", 0.0)) for g, _ in rows]),
    fn("ZR", "Float", [f(g.get("zr", 0.0)) for g, _ in rows]),
    fn("Kind", "Int32", [str(KIND[g["kind"]]) for g, _ in rows]),
    fn("Key", "String", [q(g["key"]) for g, _ in rows]),
    fn("Early", "Int32", [str(g["early"]) for g, _ in rows]),
    "  // 'FACT f' (> 0), 'NOFACT f' (== 0), 'FACTGE f n', 'SHARD LocKey#n' (in the journal), 'AFTER id' (closed or gone); ';'-joined",
    fn("Pre", "String", [q(";".join(g["pre"])) for g, _ in rows]),
    fn("Line", "String", [q(l) for _, l in rows]),
    fn("Loc", "String", [q(g["loc"]) for g, _ in rows]),
    "}",
    "",
]
out = os.path.join(H, "main", "r6", "scripts", "WhispersNC", "WNC_Data.reds")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(src))

rv = [
    "WHISPERS OF NIGHT CITY (NETdir://nc.whispers) - every rumour line, for review",
    'Edit data\\rumours.txt, then python gen_data.py. Each gem shows: "<line>" - <location>.',
    "",
]
for k in pools:
    rv.append("== POOL [%s] (%d lines, used by %d gems)" % (k, len(pools[k]), seen[k]))
    rv += ["  %2d. %s" % (i + 1, s) for i, s in enumerate(pools[k])]
    rv.append("")
rv.append(
    "== ALL %d GEMS (id, set, kind, pool, rumour as shown on the site and on the map pin)"
    % len(rows)
)
for g, line in rows:
    rv.append(
        '%3d %-7s %-5s [%s] "%s" - %s'
        % (g["id"], g["set"], g["kind"], g["pool"], line, g["loc"])
    )
open(
    os.path.join(H, "data", "RUMOURS_review.txt"), "w", encoding="utf-8", newline="\r\n"
).write("\n".join(rv) + "\n")
print("gems", len(rows), "dogtown from", FIRST_DT, seen)
